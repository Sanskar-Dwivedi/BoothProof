// Run with Playwright CLI: run-code --filename scripts/browser-workflow.js
// Uses only the isolated server at 127.0.0.1:4174 and server-generated Demo fixtures.
async (page) => {
  const check=(condition,message)=>{if(!condition)throw new Error(message);};
  const passed=[],errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const base='http://127.0.0.1:4174',number='BROWSER-'+Date.now();
  await page.unroute('**/api/payments/*/allocate');
  await page.setViewportSize({width:1366,height:900});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto(base);
  await page.getByRole('button',{name:'New invoice',exact:true}).click();
  const form=page.locator('#invoice-form');
  for(const [name,value] of Object.entries({invoice_number:number,client:'Browser QA Studio',title:'Recovery browser verification',amount:'50.00',deposit_amount:'30.00',due_date:'2026-12-01'})) await form.locator(`[name="${name}"]`).fill(value);
  await form.getByRole('button',{name:'Create invoice'}).click();
  await page.getByRole('heading',{name:'Recovery browser verification'}).waitFor();
  const checkout=await page.getByRole('link',{name:'Open statement',exact:true}).getAttribute('href');
  check(Boolean(checkout),'No customer statement link');
  await page.getByText('Practice invoice payments · offline',{exact:true}).click();
  await page.getByRole('button',{name:'Practice reference-free 30 USDC',exact:true}).click();
  check((await page.locator('#payment-content .invoice-balances').innerText()).includes('0.00'),'Recovery incorrectly credited invoice');
  passed.push('Reference-free practice payment leaves invoice credit at zero');
  await page.getByRole('link',{name:'Recovery',exact:true}).click();
  const article=page.locator('.recovered-payment').filter({hasText:number});
  await article.waitFor();
  const signature=await article.getByRole('button',{name:'Copy signature',exact:true}).getAttribute('data-copy');
  const customer=await page.context().newPage();await customer.goto(base+checkout);
  await customer.getByText('Your reported transfer is verified and awaits merchant allocation. It has not reduced this balance. Wait for allocation before paying again.',{exact:true}).waitFor();
  check((await customer.locator('.customer-amount').innerText()).includes('50.00'),'Unallocated recovery reduced the customer balance');
  await customer.close();await page.bringToFront();
  await article.getByRole('button',{name:'Assign to invoice'}).click();
  const dialog=page.locator('dialog.decision-dialog'),allocation=dialog.locator('#allocation-form');
  check(await allocation.locator('select').inputValue()==='','Allocation preselected an invoice');
  await allocation.locator('select').selectOption({label:number+' · Browser QA Studio'});
  const preview=await dialog.locator('#allocation-preview').innerText();
  check(preview.includes('30.00 USDC')&&preview.includes('20.00 USDC'),'Assignment preview is incorrect');
  const note='Browser QA private operator note';await allocation.locator('textarea').fill(note);
  await page.waitForTimeout(5_300);
  check(await allocation.locator('textarea').inputValue()===note,'Polling erased operator note');
  const ids=[];let dropped=false;
  await page.route('**/api/payments/*/allocate',async route=>{
    ids.push(route.request().postDataJSON().request_id);
    const response=await route.fetch();
    if(!dropped){dropped=true;await route.abort('failed');}else await route.fulfill({response});
  });
  await allocation.getByRole('button',{name:'Confirm assignment',exact:true}).click();
  await dialog.locator('[data-decision-error]').filter({hasText:'offline'}).waitFor();
  await allocation.getByRole('button',{name:'Retry saved decision',exact:true}).click();
  await dialog.waitFor({state:'hidden'});await page.unroute('**/api/payments/*/allocate');
  check(ids.length===2&&ids[0]===ids[1],'A network retry changed the allocation request ID');
  passed.push('Explicit assignment preview, operator draft preservation and lost-response idempotency');
  await page.goto(base+checkout);
  await page.getByRole('button',{name:'Simulate remaining balance',exact:true}).waitFor();
  check((await page.locator('.customer-amount').innerText()).includes('20.00'),'Customer balance is not 20 USDC');
  check(!await page.getByRole('button',{name:/^Pay deposit/}).count(),'Satisfied deposit is still offered');
  await page.getByText('I already paid',{exact:true}).click();
  await page.locator('#signature').fill(signature);
  await page.locator('#signature-form').getByRole('button',{name:'Verify',exact:true}).click();
  await page.waitForTimeout(5_300);
  check(await page.locator('#signature').inputValue()===signature,'Polling erased a customer signature');
  const posts=[];const observer=request=>{if(request.method()==='POST')posts.push(request.url());};page.on('request',observer);
  await page.waitForTimeout(5_300);page.off('request',observer);
  check(posts.length===0,'Routine browser polling performed verification POSTs');
  const safe=await page.request.get(base+'/api/checkout/'+checkout.split('/').at(-1));
  check(!(await safe.text()).includes(note),'Customer endpoint leaked merchant note');
  passed.push('Customer projection, satisfied deposit, signature draft and read-only polling');
  await page.locator('#signature').focus();
  const payer=await page.context().newPage();await payer.goto(base+checkout);
  await payer.getByRole('button',{name:'Simulate remaining balance',exact:true}).click();await payer.getByText('Reconciled',{exact:true}).waitFor();
  await payer.close();await page.bringToFront();await page.waitForTimeout(5_300);
  await page.getByText('Reconciled',{exact:true}).waitFor();
  check(await page.locator('#signature').inputValue()===signature,'A financial refresh erased the signature draft');
  check(await page.evaluate(()=>document.activeElement.id==='signature'),'A financial refresh lost signature keyboard focus');
  await page.locator('#signature-form').getByRole('button',{name:'Verify',exact:true}).click();
  check((await page.locator('.customer-amount').innerText()).includes('0.00'),'Signature replay changed remaining balance');
  await page.reload();await page.getByText('Reconciled',{exact:true}).waitFor();
  await page.screenshot({path:'output/playwright/workspace-simulated-customer-settled.png',fullPage:true});
  passed.push('20 USDC checkout, duplicate replay and reload preserve settlement');
  await page.setViewportSize({width:360,height:800});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Customer layout overflows 360px');
  await page.screenshot({path:'output/playwright/workspace-simulated-mobile-checkout.png',fullPage:true});
  await page.goto(base+'/#invoices');await page.getByRole('button',{name:'Inspect invoice '+number,exact:true}).click();
  await page.getByRole('button',{name:'Reverse assignment',exact:true}).click();
  await dialog.locator('textarea').fill('Browser QA reversal; proof must remain');
  await dialog.getByRole('button',{name:'Confirm reversal',exact:true}).click();await dialog.waitFor({state:'hidden'});
  await page.waitForTimeout(4_500);
  check((await page.locator('#payment-content .invoice-balances').innerText()).includes('30.00'),'Reversal did not restore outstanding balance');
  await page.getByRole('link',{name:'Recovery',exact:true}).click();
  await page.locator('.recovered-payment').filter({hasText:number}).waitFor();
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Recovery layout overflows 360px');
  await page.screenshot({path:'output/playwright/workspace-simulated-mobile-recovery.png',fullPage:true});
  await page.goto(base+'/#invoices');
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Invoice layout overflows 360px');
  await page.screenshot({path:'output/playwright/workspace-simulated-mobile-invoices.png',fullPage:true});
  passed.push('Manual reversal retains proof; invoice, recovery and checkout fit 360px');
  check(errors.length===0,'Browser runtime errors: '+errors.join('; '));
  await page.setViewportSize({width:1366,height:900});
  return {passed,invoice:number,checkout,signature,runtimeErrors:errors};
}
